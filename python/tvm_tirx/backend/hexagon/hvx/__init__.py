"""Hexagon intrinsics as data: the ``T.hvx`` dialect and the scalar cache ops.

:mod:`.table` lists every C intrinsic of the Hexagon programming interface
that has an LLVM intrinsic, generated by :mod:`.gen_table` from LLVM's own
definitions. Importing this package registers each row as an Op through
:mod:`.engine`:

- ``tirx.hvx.<name>``, written ``T.hvx.<name>``: the HVX vector instructions,
  such as ``T.hvx.Vw_vadd_VwVw`` for C's ``Q6_Vw_vadd_VwVw``.
- ``tirx.hexagon.<name>``, written ``T.hexagon.<name>``: the scalar cache and
  prefetch instructions that HVX code needs around DMA and loads, such as
  ``T.hexagon.l2fetch_AP`` and ``T.hexagon.dccleaninva_A``.
"""

